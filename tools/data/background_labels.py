"""Generate label files for recordings with nothing to find: Tier 1's background spans (PLAN 5.1 negatives).

These are generated by construction, not labelled by hand; this script, its inputs and each window's labeller field
are their provenance, and `label_sheet.py check` is their review.
- The three Essex xeno-canto recordings hold jets but no propeller pass, so each is one absent window. "Absent"
  there means no propeller pass: a detection on a jet is the E5 false alarm item 6's curve must show.
- AeroSonicDB's six continuous soundscape hours carry a class every 5 s (environment_class_mappings.csv: 0 no
  aircraft, 1 aircraft audible, "ignore" at event boundaries). Each run of 0 lasting at least MIN_RUN_S becomes an
  absent window less GUARD_S at each end, since the marks are 5 s coarse and a distant tail may outlast the ignore
  buffer; everything else is masked.

usage: background_labels.py OUT_DIR       writes the nine label files, refusing to overwrite any"""
import csv
import hashlib
import io
import json
import os
import sys
import zipfile
from pathlib import Path

DATA = Path(os.environ.get("DOPPLERTRACK_DATA", Path.home() / "data" / "dopplertrack"))
DATE = "2026-11-04"
MIN_RUN_S, GUARD_S, MARK_S = 60.0, 10.0, 5.0
ESSEX = [("XC990819_2025-04-20_0510", 5539.886), ("XC990820_2025-04-20_0510", 3657.683),
         ("XC986433_2025-04-07_0545", 2754.515)]   # ffprobe durations, rounded as the windows are
AEROSONIC = "raw/audio/aerosonicdb/zenodo-10215080"
ESSEX_LABELLER = "by construction: a jet-only recording, no propeller pass (data root MANIFEST.md, xeno-canto section)"
AEROSONIC_LABELLER = "generated from AeroSonicDB's 5 s marks by tools/data/background_labels.py"


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while block := f.read(1 << 24):
            h.update(block)
    return h.hexdigest()


def window(wid, cls, start, end, labeller, notes):
    return {"id": wid, "class": cls, "start": round(start, 3), "end": round(end, 3), "lines": [], "harmonics": 0,
            "labeller": labeller, "blind": True, "date": DATE, "notes": notes}


def essex(name: str, duration: float) -> dict:
    src = f"raw/audio/xenocanto/{name}.mp3"
    return {"format": 1,
            "recording": {"id": name, "source": src, "sha256": sha256(DATA / src), "t0_utc": None, "case": None},
            "span": [0.0, duration], "sheets": None,
            "windows": [window(f"{name[:8].lower()}-a01", "absent", 0.0, duration, ESSEX_LABELLER,
                               "no propeller pass within 12 km; 9-14 jet passes, whose detections are false alarms (E5)")],
            "associations": []}


def aerosonic(column: int, marks: list[str]) -> dict:
    """One soundscape hour: runs of 0 at least MIN_RUN_S long, less GUARD_S each end, absent; the rest masked."""
    end_s = MARK_S * len(marks)
    runs, k = [], 0
    while k < len(marks):
        j = k
        while j < len(marks) and marks[j] == marks[k]:
            j += 1
        runs.append((marks[k], k * MARK_S, j * MARK_S))
        k = j
    absent = [(a + GUARD_S, b - GUARD_S) for v, a, b in runs if v == "0" and b - a >= MIN_RUN_S]
    windows, cursor, n = [], 0.0, 0
    for a, b in absent:
        if a > cursor:
            n += 1
            windows.append(window(f"asd{column + 1}-m{n:02d}", "masked", cursor, a, AEROSONIC_LABELLER,
                                  "aircraft audible, an event boundary, a guard or a short quiet run"))
        n += 1
        windows.append(window(f"asd{column + 1}-a{n:02d}", "absent", a, b, AEROSONIC_LABELLER,
                              f"marked 0 (no aircraft) for {b - a + 2 * GUARD_S:.0f} s; {GUARD_S:.0f} s guard each end"))
        cursor = b
    if cursor < end_s:
        n += 1
        windows.append(window(f"asd{column + 1}-m{n:02d}", "masked", cursor, end_s, AEROSONIC_LABELLER,
                              "aircraft audible, an event boundary, a guard or a short quiet run"))
    member = f"env_audio/{column + 1}_AUDIO.wav"
    return {"format": 1,
            "recording": {"id": f"aerosonicdb_env_{column + 1}", "source": f"{AEROSONIC}/env_audio.zip",
                          "member": member, "sha256": sha256(DATA / AEROSONIC / "env_audio.zip"), "t0_utc": None,
                          "case": None, "marks": f"{AEROSONIC}/environment_class_mappings.csv, column {column}"},
            "span": [0.0, end_s], "sheets": None, "windows": windows, "associations": []}


def main():
    out = Path(sys.argv[1])
    docs = {f"{name}-0000-{int(d)}.json": essex(name, d) for name, d in ESSEX}
    with zipfile.ZipFile(DATA / AEROSONIC / "env_audio.zip") as z:
        assert all(f"env_audio/{n}_AUDIO.wav" in z.namelist() for n in range(1, 7))
    rows = list(csv.reader(io.StringIO((DATA / AEROSONIC / "environment_class_mappings.csv").read_text())))
    for c in range(6):
        docs[f"aerosonicdb_env_{c + 1}-0000-3600.json"] = aerosonic(c, [r[c] for r in rows[1:]])
    if taken := [n for n in docs if (out / n).exists()]:
        sys.exit("refusing to overwrite: " + ", ".join(taken))
    for name, doc in docs.items():
        (out / name).write_text(json.dumps(doc, indent=1) + "\n")
        absent = sum(w["end"] - w["start"] for w in doc["windows"] if w["class"] == "absent")
        print(f"{name}: {len(doc['windows'])} windows, {absent:.0f} s absent of {doc['span'][1]:.0f} s")


if __name__ == "__main__":
    main()
